import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE??'playwright');
const launch=process.env.CHROMIUM_EXECUTABLE ? {executablePath:process.env.CHROMIUM_EXECUTABLE} : {};
const browser=await chromium.launch(launch);
const url=process.env.DASHBOARD_URL??'http://127.0.0.1:8080';
const shots=process.env.DASHBOARD_SHOTS;
if(shots)await mkdir(shots,{recursive:true});
try{
  const desktop=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];
  desktop.on('pageerror',error=>errors.push(error.message));
  await desktop.goto(url);
  assert.equal(await desktop.locator('html').getAttribute('dir'),'rtl');
  if(shots)await desktop.screenshot({path:shots+'/desktop-rtl-light.jpg',type:'jpeg',quality:88,fullPage:true});
  await desktop.keyboard.press('Tab');
  assert.equal(await desktop.locator(':focus').textContent(),'انتقل إلى المحتوى');
  await desktop.locator('#theme').click();
  assert.equal(await desktop.locator('html').getAttribute('data-theme'),'dark');
  if(shots)await desktop.screenshot({path:shots+'/desktop-rtl-dark.jpg',type:'jpeg',quality:88,fullPage:true});
  await desktop.locator('#hub-button').focus();
  await desktop.keyboard.press('Enter');
  assert.equal(await desktop.locator(':focus').getAttribute('id'),'hub-search');
  await desktop.keyboard.type('JED');
  assert.match(await desktop.locator('#hub-options').textContent(),/جدة/);
  await desktop.keyboard.press('Tab');
  await desktop.keyboard.press('Enter');
  await desktop.locator('#hub-dialog').waitFor({state:'hidden'});
  assert.equal(await desktop.locator(':focus').getAttribute('id'),'hub-button');
  assert.equal(await desktop.locator('#table-body tr').count(),2);
  await desktop.locator('#language').click();
  assert.equal(await desktop.locator('html').getAttribute('lang'),'en');
  assert.equal(await desktop.locator('html').getAttribute('dir'),'ltr');
  assert.equal(await desktop.locator('#table-body tr').count(),2);
  await desktop.getByRole('button',{name:'View MC-4181'}).focus();
  await desktop.keyboard.press('Enter');
  assert.match(await desktop.locator('#detail-body').textContent(),/Spare parts/);
  await desktop.keyboard.press('Escape');
  await desktop.locator('#detail-dialog').waitFor({state:'hidden'});
  assert.equal(await desktop.locator(':focus').getAttribute('aria-label'),'View MC-4181');
  await desktop.locator('#search').fill('no-such-row');
  assert.match(await desktop.locator('#table-body').textContent(),/No matching shipments/);
  await desktop.locator('#reset').click();
  await desktop.locator('#sort').click();
  assert.equal(await desktop.locator('#sort-head').getAttribute('aria-sort'),'ascending');
  assert.match(await desktop.locator('#table-body tr').first().textContent(),/MC-4174/);
  await desktop.locator('#next').click();
  assert.equal(await desktop.locator('#table-body tr').count(),4);
  assert.deepEqual(errors,[]);
  await desktop.locator('#theme').click();
  if(shots)await desktop.screenshot({path:shots+'/desktop-ltr-light.jpg',type:'jpeg',quality:88,fullPage:true});

  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1,hasTouch:true});
  await mobile.goto(url);
  await mobile.locator('#results').waitFor();
  const overflow=await mobile.evaluate(()=>({page:document.documentElement.scrollWidth,view:innerWidth,
    table:document.querySelector('.table-frame').scrollWidth,tableView:document.querySelector('.table-frame').clientWidth}));
  assert.equal(overflow.page,overflow.view);
  assert.ok(overflow.table>overflow.tableView);
  if(shots)await mobile.screenshot({path:shots+'/mobile-rtl-light.jpg',type:'jpeg',quality:88,fullPage:true});
  console.log('Passed RTL/LTR, dark mode, keyboard focus, dialogs, search, filter, empty, sort, pagination, and mobile overflow.');
}finally{await browser.close();}
